"""
stage1_tables.py
================
Renders the Checkpoint-1 tables from the saved result files (no numbers are
typed by hand).  Writes results/stage1/checkpoint1_tables.md.
"""
import json
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results", "stage1")
CANDS = [("const", "best constant r"), ("cliplin_LS", "clip-linear, least squares"),
         ("cliplin_TAU", "clip-linear, tau-optimised"), ("logistic_TAU", "logistic, tau-optimised"),
         ("isotonic", "isotonic (monotone)"), ("lin2[pesc_M+inter_arc_frac]", "2-feature linear (diagnostic)"),
         ("gbm[all observable]", "boosted trees, all observables (diagnostic)")]


def fmt_p(p):
    if p is None or (isinstance(p, float) and np.isnan(p)):
        return "-"
    return f"{p:.1e}" if p < 1e-3 else f"{p:.3f}"


def table(gt):
    s = pd.read_csv(os.path.join(RES, f"summary_{gt}.csv"))
    fits = {d["name"]: d for d in json.load(open(os.path.join(RES, f"fits_{gt}.json")))}
    diag = json.load(open(os.path.join(RES, f"diagnostics_{gt}.json")))
    panels = [p for p in ["test", "scale", "topo", "real"] if (s["panel"] == p).any()]
    lines = [f"### Ground truth: {gt}", "",
             f"Calibration panel: {diag['n_calib_instances']} instances from {diag['n_calib_bases']} graphs. "
             f"corr(Pbar, r*): Pearson {diag['corr_pesc_rstar']['pearson']:+.3f}, Spearman "
             f"{diag['corr_pesc_rstar']['spearman']:+.3f}; within graphs {diag['within_between']['within']:+.3f}, "
             f"between graph means {diag['within_between']['between']:+.3f}. "
             f"Test-retest of r*: {diag['noise_ceiling'].get('test_retest_pearson', float('nan')):.3f}. "
             f"r*(Kendall) vs r*(Spearman): Pearson {diag['rstar_kendall_vs_spearman']['pearson']:.3f}.", ""]
    head = "| rule | formula | fit r | fit rho | RMSE | CV tau |" + "".join(
        f" {p} tau | {p} rho | {p} gap | {p} p vs const |" for p in panels)
    lines += [head, "|" + "---|" * (head.count("|") - 1)]
    cal = s[s["panel"] == "calib"].set_index("rule")
    for name, lab in CANDS:
        if name not in cal.index:
            continue
        c = cal.loc[name]
        f = fits.get(name, {}).get("formula", "")
        row = (f"| {lab} | `{f}` | {c['pearson_fx_rstar']:.3f} | {c.get('rho_rank_fx_rstar', np.nan):.3f} | "
               f"{c['rmse_r']:.3f} | {c['cv_tau']:.4f} |")
        for p in panels:
            q = s[(s["panel"] == p) & (s["rule"] == name)]
            if len(q) == 0:
                row += " - | - | - | - |"
                continue
            q = q.iloc[0]
            pv = q.get("vs_const_p", np.nan) if name != "const" else np.nan
            row += f" {q['tau']:.4f} | {q['rho']:.4f} | {100 * q['gap_closed_vs_can']:.0f}% | {fmt_p(pv)} |"
        lines.append(row)
    ref = "| reference | | | | | |"
    for p in panels:
        q = s[(s["panel"] == p) & (s["rule"] == "const")].iloc[0]
        r0 = s[(s["panel"] == p) & (s["rule"] == "PageRank_r0")].iloc[0]
        ref += f" oracle {q['tau_oracle']:.4f} / canonical {q['tau_canonical']:.4f} / r=0 {r0['tau']:.4f} | | | |"
    lines += [ref, "", "gap = share of the canonical-to-oracle tau gap closed; p vs const = Wilcoxon signed-rank "
                       "on per-graph mean tau differences (rule minus best calibration constant).", ""]
    return "\n".join(lines)


def main():
    out = ["# Checkpoint 1 tables (generated by stage1_tables.py)", ""]
    for gt in ["NCD", "POP", "PR", "SELF"]:
        if os.path.exists(os.path.join(RES, f"summary_{gt}.csv")):
            out.append(table(gt))
    dec = json.load(open(os.path.join(RES, "decomposition.json")))
    out += ["### Variance decomposition of r* (calibration panel)", "",
            "| truth | graph | level | graph+level | hidden params + level (CV) | all observables, ridge (CV) | Pbar alone (CV) |",
            "|---|---|---|---|---|---|---|"]
    for gt in ["NCD", "PR", "POP", "SELF"]:
        d = dec[gt]
        out.append(f"| {gt} | {d['r2_base']:.2f} | {d['r2_level']:.2f} | {d['r2_base_level']:.2f} | "
                   f"{d['r2_hidden_cv']:.2f} | {d['r2_observable_ridge_cv']:.2f} | {d['r2_pesc_cv']:.2f} |")
    path = os.path.join(RES, "checkpoint1_tables.md")
    open(path, "w").write("\n".join(out) + "\n")
    print(open(path).read())


if __name__ == "__main__":
    main()
