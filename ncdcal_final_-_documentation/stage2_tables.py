"""
stage2_tables.py
================
Renders the Checkpoint-2 tables from the saved Stage 2 result files (no number is
typed by hand).  Writes results/stage2/checkpoint2_tables.md.
"""
import json
import os

import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results", "stage2")
PANELS = ["test", "scale", "topo", "real"]
LAB = {"const": "best constant alpha", "cliplin_LS": "clip-linear, least squares",
       "cliplin_free_LS": "clip-linear free bounds, LS", "logistic_LS": "logistic, LS",
       "isotonic": "isotonic (monotone)", "cliplin_TAU": "clip-linear, tau-optimised",
       "cliplin_free_TAU": "clip-linear free bounds, tau-opt.", "logistic_TAU": "logistic, tau-optimised",
       "gbm[observables]": "boosted trees, all observables (diagnostic ceiling)",
       "budget_LS": "displacement budget c/(c+x), LS", "budget_TAU": "displacement budget c/(c+x), tau-opt."}


def fp(p):
    if p is None or (isinstance(p, float) and np.isnan(p)):
        return "-"
    return f"{p:.1e}" if p < 1e-3 else f"{p:.3f}"


def rule_table(summ, fits, diag, r, t, feat):
    s = summ[(summ["r_setting"] == r) & (summ["truth"] == t) & (summ["feature"] == feat)]
    if s.empty:
        return ""
    info = [c for c in diag["configs"] if c["r_setting"] == r and c["truth"] == t and c["feature"] == feat][0]
    fd = {d["name"]: d for d in fits[f"{r}|{t}|{feat}"]}
    panels = [p for p in PANELS if (s["panel"] == p).any()]
    wb, ac = info["within_between"], info["alpha_star_calib"]
    out = [f"#### g fitted on `{feat}`: r-setting `{r}`, truth `{t}`", "",
           f"Calibration: {info['n_calib']} instances; alpha* = {ac['mean']:.3f} +- {ac['sd']:.3f} "
           f"(at 0.40: {100 * ac['at_lower']:.0f}%, at 0.99: {100 * ac['at_upper']:.0f}%). "
           f"corr({feat}, alpha*): pooled {wb['pooled']:+.3f}, within graphs {wb['within']:+.3f}, "
           f"between graph means {wb['between']:+.3f}.", ""]
    head = "| rule | formula | fit r | RMSE | CV tau |" + "".join(
        f" {p} tau | {p} gap | {p} vs a=0.85 | {p} vs const a |" for p in panels)
    out += [head, "|" + "---|" * (head.count("|") - 1)]
    cal = s[s["panel"] == "calib"].set_index("rule")
    for name in cal.index:
        c = cal.loc[name]
        row = (f"| {LAB.get(name, name)} | `{fd.get(name, {}).get('formula', '')}` | {c['corr_ghat_astar']:.3f} | "
               f"{c['rmse_alpha']:.3f} | {c['cv_tau']:.4f} |")
        for p in panels:
            q = s[(s["panel"] == p) & (s["rule"] == name)]
            if q.empty:
                row += " - | - | - | - |"
                continue
            q = q.iloc[0]
            pc = f"{q['d_vs_const']:+.4f} (p {fp(q['p_vs_const'])})" if name != "const" else "-"
            p085 = f"{q['d_vs_085']:+.4f} (p {fp(q['p_vs_085'])})"
            row += f" {q['tau']:.4f} | {100 * q['gap_closed_vs_085']:.0f}% | {p085} | {pc} |"
        out.append(row)
    ref = "| reference: alpha = 0.85 / oracle | | | | |"
    for p in panels:
        q = s[(s["panel"] == p)].iloc[0]
        ref += f" {q['tau_085']:.4f} / {q['tau_oracle']:.4f} | | | |"
    out += [ref, ""]
    return "\n".join(out)


def pipeline_table(pipe, t):
    q = pipe[pipe["truth"] == t]
    if q.empty:
        return ""
    panels = [p for p in ["calib"] + PANELS if (q["panel"] == p).any()]
    pols = list(dict.fromkeys(q["policy"]))
    head = "| policy |" + "".join(f" {p} tau | {p} vs NG13(0.85) | {p} vs NG13(0.95) |" for p in panels)
    out = [f"#### Truth `{t}`", "", head, "|" + "---|" * (head.count("|") - 1)]
    for pol in pols:
        row = f"| {pol} |"
        for p in panels:
            z = q[(q["panel"] == p) & (q["policy"] == pol)]
            if z.empty:
                row += " - | - | - |"
                continue
            z = z.iloc[0]
            row += (f" {z['tau']:.4f} | {z['d_vs_ng13_085']:+.4f} (p {fp(z['p_vs_ng13_085'])}) |"
                    f" {z['d_vs_ng13_095']:+.4f} (p {fp(z['p_vs_ng13_095'])}) |")
        out.append(row)
    out.append("")
    return "\n".join(out)


def main():
    summ = pd.read_csv(os.path.join(RES, "summary.csv"))
    pipe = pd.read_csv(os.path.join(RES, "pipelines.csv"))
    fits = json.load(open(os.path.join(RES, "fits.json")))
    diag = json.load(open(os.path.join(RES, "diagnostics.json")))
    dec = json.load(open(os.path.join(RES, "decomposition.json")))
    out = ["# Checkpoint 2 tables (generated by stage2_tables.py)", "",
           f"Numerical check: max over all instances and r-settings of |mean_v Sigma_in(v) - 1| = "
           f"{diag['checks']['max_abs_mean_sigma_minus_1']:.1e} ({diag['checks']['n_instances']} instances).", "",
           "## 1. Candidate rules alpha = g(h) (primary: r = Stage 1 rule, truth NCD)", "",
           "gap = share of the (alpha = 0.85) -> oracle tau gap closed; 'vs' columns = mean tau difference "
           "(rule minus comparator) with the Wilcoxon signed-rank p over per-graph means.", ""]
    out.append(rule_table(summ, fits, diag, "rule", "NCD", "h_rule"))
    out.append(rule_table(summ, fits, diag, "rule", "NCD", "hv_rule"))
    out += ["## 2. Sensitivity truths (g refitted per truth)", ""]
    for r, t in [("rule", "TOT"), ("rule", "Q"), ("popLS", "POP"), ("popTAU", "POP"), ("ng13", "NCD95")]:
        out.append(rule_table(summ, fits, diag, r, t, f"h_{r}"))
    out += ["## 3. Complete pipelines vs the static [NG13] baselines",
            "", "All rules fitted on the calibration panel under the primary truth (NCD) and evaluated unchanged "
            "under every truth. NG13(0.85) = (r = 0.10/0.85, alpha = 0.85); NG13(0.95) = (r = 0.10/0.95, alpha = 0.95), "
            "[NG13]'s Section 4 setting. tau = mean over instances; differences = mean over graphs of the per-graph "
            "mean difference (each graph weighted equally; this is the unit of the Wilcoxon test). The two "
            "weightings coincide on the synthetic panels and differ on the real panel, where cnr-2000 has 14 "
            "instances and the other graphs 28.", ""]
    for t in ["NCD", "NCD95", "TOT", "POP", "Q"]:
        out.append(pipeline_table(pipe, t))
    out += ["## 4. Anchoring, censoring and variance decomposition of alpha* (calibration panel)", "",
            "| r, truth | alpha* mean +- sd | anchor on A1.0 | graph | level | graph+level | hidden+level (CV) | "
            "observables incl. h (CV) | h alone (CV) |", "|---|---|---|---|---|---|---|---|---|"]
    for k, d in dec.items():
        out.append(f"| {k} | {d['mean']:.3f} +- {d['sd']:.3f} | {d['anchor_A10']['mean']:.3f} | {d['r2_base']:.2f} | "
                   f"{d['r2_level']:.2f} | {d['r2_base_level']:.2f} | {d['r2_hidden_cv']:.2f} | "
                   f"{d['r2_observable_ridge_cv']:.2f} | {d['r2_h_cv']:.2f} |")
    out.append("")
    path = os.path.join(RES, "checkpoint2_tables.md")
    open(path, "w").write("\n".join(out) + "\n")
    print(open(path).read())


if __name__ == "__main__":
    main()
